//! Tiny 5x7 bitmap font used by the lock notice and the `--debug` overlay.

use crate::framebuffer::Frame;

pub fn fill(frame: &mut Frame, color: [u8; 4]) {
    let stride = frame.stride();
    for y in 0..frame.height as usize {
        let row = &mut frame.bgra[y * stride..y * stride + frame.width as usize * 4];
        for px in row.chunks_exact_mut(4) {
            px.copy_from_slice(&color);
        }
    }
}

pub fn fill_rect(frame: &mut Frame, x: u32, y: u32, w: u32, h: u32, color: [u8; 4]) {
    let stride = frame.stride();
    let x0 = x.min(frame.width) as usize;
    let x1 = (x + w).min(frame.width) as usize;
    let y0 = y.min(frame.height) as usize;
    let y1 = (y + h).min(frame.height) as usize;
    for yy in y0..y1 {
        let row = &mut frame.bgra[yy * stride..yy * stride + frame.width as usize * 4];
        for px in row[x0 * 4..x1 * 4].chunks_exact_mut(4) {
            px.copy_from_slice(&color);
        }
    }
}

pub fn text_width(text: &str, scale: u32) -> u32 {
    text.chars().count() as u32 * 6 * scale.max(1)
}

/// Draws `text` at (x, y); returns the advance width in pixels.
pub fn draw_text(
    frame: &mut Frame,
    x: u32,
    y: u32,
    text: &str,
    scale: u32,
    color: [u8; 4],
) -> u32 {
    let scale = scale.max(1);
    let mut cx = x;
    for ch in text.chars() {
        draw_char(frame, cx, y, ch, scale, color);
        cx += 6 * scale;
    }
    text_width(text, scale)
}

fn draw_char(frame: &mut Frame, x: u32, y: u32, ch: char, scale: u32, color: [u8; 4]) {
    let Some(rows) = glyph(ch) else {
        return;
    };
    for (ry, bits) in rows.iter().enumerate() {
        for rx in 0..5u32 {
            if bits & (1 << (4 - rx)) != 0 {
                fill_rect(
                    frame,
                    x + rx * scale,
                    y + ry as u32 * scale,
                    scale,
                    scale,
                    color,
                );
            }
        }
    }
}

/// Minimal 5x7 uppercase font (rows are 5-bit, MSB = leftmost column).
